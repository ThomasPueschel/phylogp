test_that("fits are pooled across trees and aligned by species", {
  skip_on_cran()
  skip_if_not_installed("cmdstanr")
  skip_if(is.null(tryCatch(cmdstanr::cmdstan_path(), error = function(e) NULL)))
  set.seed(31)
  base <- ape::rcoal(25)
  trees <- c(base, ape::rcoal(25, tip.label = sample(base$tip.label)))
  y <- kernel_simulate(k_bm() + k_white(), base)[, 1]
  d <- data.frame(y = y, row.names = names(y))
  ft <- suppressMessages(phylo_gp_trees(y ~ 1, d, trees, k_bm() + k_white(),
                                        chains = 2, iter_warmup = 200, iter_sampling = 200))
  expect_s3_class(ft, "phylogp_trees")
  expect_equal(dim(coef(ft)), c(2, 3))
  s <- summary(ft)
  pooled <- c(ft$fits[[1]]$fit$draws("bm1_sigma"), ft$fits[[2]]$fit$draws("bm1_sigma"))
  expect_equal(s$mean[s$parameter == "bm1_sigma"], mean(pooled))
  lo <- suppressWarnings(loo(ft))
  expect_equal(nrow(lo$pointwise), 25)
  # equal weights: the mean over trees of the per-tree left-out densities
  pt <- attr(lo, "per_tree")
  expect_length(pt, 2)
  e <- cbind(pt[[1]]$pointwise[, "elpd_loo"], pt[[2]]$pointwise[, "elpd_loo"])
  expect_equal(unname(lo$pointwise[, "elpd_loo"]), unname(log(rowMeans(exp(e)))))
  expect_equal(lo$estimates["elpd_loo", "Estimate"], sum(log(rowMeans(exp(e)))))
  expect_true(all(lo$pointwise[, "p_loo"] > -1))
  expect_s3_class(loo::loo_compare(lo, lo), "compare.loo")
  expect_true(all(ft$fits[[1]]$tree$tip.label %in% attr(lo, "species")))
  fm <- suppressMessages(phylo_gp_trees(y ~ 1, d, trees, k_lambda(), method = "optimize"))
  expect_true("between_tree_sd" %in% names(summary(fm)))
})
